@dataclass(frozen=True)
class DemandQuery:
    id: str
    text: str
    qtype: str  # keyword | semantic | mixed
    difficulty: str  # easy | medium | hard
    segment: str
    form: str  # keyword | phrase | sentence
    must: dict[str, Any]
    should: dict[str, Any] = field(default_factory=dict)
    unanswerable: tuple[str, ...] = ()

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["unanswerable"] = list(self.unanswerable)
        return d


def _d(n: int, text: str, qtype: str, difficulty: str, segment: str, form: str, must: dict[str, Any],
       should: dict[str, Any] | None = None, unanswerable: tuple[str, ...] = ()) -> DemandQuery:
    return DemandQuery(f"d{n:03d}", text, qtype, difficulty, segment, form, must, should or {}, unanswerable)


